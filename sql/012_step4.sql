-- Step 4 backend: atomic order placement + settings/table support.
-- Safe to re-run (CREATE OR REPLACE / IF NOT EXISTS). No reset, no data purge.

create extension if not exists pgcrypto;

-- Every table gets a random QR token when created from the admin screen.
alter table public.dining_tables
  alter column qr_token set default encode(gen_random_bytes(16), 'hex');

create unique index if not exists dining_tables_qr_token_key
  on public.dining_tables (qr_token) where qr_token is not null;

-- Atomic order placement. Prices are resolved from menu_items inside the same
-- transaction as the order + item inserts, so a price change cannot split a
-- basket. public_token is generated by the DB and never derived from order_no.
create or replace function public.create_order(
  p_table_id bigint,
  p_items jsonb,
  p_notes text default null,
  p_placed_by bigint default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_table    dining_tables%rowtype;
  v_menu     menu_items%rowtype;
  v_order    orders%rowtype;
  v_item     jsonb;
  v_lines    jsonb := '[]'::jsonb;
  v_total    numeric(12,2) := 0;
  v_price    numeric(12,2);
  v_qty      integer;
  v_line     numeric(12,2);
  v_notes    text;
begin
  if exists (
    select 1 from public.settings
     where key = 'ordering_enabled' and (value #>> '{}')::boolean = false
  ) then
    raise exception 'ordering_disabled' using errcode = 'P0001';
  end if;

  if p_table_id is null then
    raise exception 'table_required' using errcode = '22023';
  end if;

  select * into v_table
    from public.dining_tables
   where id = p_table_id and active = true;
  if not found then
    raise exception 'table_not_found' using errcode = '22023';
  end if;

  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'items_required' using errcode = '22023';
  end if;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_qty := nullif(v_item ->> 'quantity', '')::integer;
    if v_qty is null or v_qty <= 0 or v_qty > 100 then
      raise exception 'invalid_quantity' using errcode = '22023';
    end if;

    if nullif(v_item ->> 'menu_item_id', '') is null then
      raise exception 'invalid_menu_item' using errcode = '22023';
    end if;

    select * into v_menu
      from public.menu_items
     where id = (v_item ->> 'menu_item_id')::bigint
       and available = true;
    if not found then
      raise exception 'menu_item_unavailable' using errcode = '22023';
    end if;

    v_price := round(v_menu.price, 2);
    v_line := round(v_price * v_qty, 2);
    v_total := v_total + v_line;
    v_notes := nullif(btrim(coalesce(v_item ->> 'notes', '')), '');

    v_lines := v_lines || jsonb_build_object(
      'menu_item_id', v_menu.id,
      'name', v_menu.name,
      'name_am', v_menu.name_am,
      'price', v_price,
      'quantity', v_qty,
      'line_total', v_line,
      'notes', v_notes
    );
  end loop;

  insert into public.orders (table_id, currency, total, special_notes, placed_by)
  values (v_table.id, 'ETB', v_total, nullif(btrim(coalesce(p_notes, '')), ''), p_placed_by)
  returning * into v_order;

  insert into public.order_items (
    order_id, menu_item_id, name_snapshot, name_am_snapshot,
    price_snapshot, quantity, line_total, notes
  )
  select
    v_order.id,
    (x ->> 'menu_item_id')::bigint,
    x ->> 'name',
    x ->> 'name_am',
    (x ->> 'price')::numeric,
    (x ->> 'quantity')::integer,
    (x ->> 'line_total')::numeric,
    x ->> 'notes'
  from jsonb_array_elements(v_lines) as x;

  return jsonb_build_object(
    'order_no', v_order.order_no,
    'public_token', v_order.public_token,
    'currency', v_order.currency,
    'total', v_order.total,
    'total_cents', (v_total * 100)::integer,
    'items', v_lines
  );
end
$fn$;

comment on function public.create_order(bigint, jsonb, text, bigint) is
  'Atomically places an order using current DB prices; returns a random public_token for the receipt.';

grant execute on function public.create_order(bigint, jsonb, text, bigint)
  to service_role, authenticated, anon;
